export function createDocumentTemplate(kind:DocumentTemplateKind):DocumentBody {
 if(kind==='blank') return {formatVersion:1,blocks:[block('paragraph')]};
 const outline=outlines[kind],label=documentTemplateOptions.find(option=>option.value===kind)!.label;
 return {formatVersion:1,blocks:[block('heading',label,{level:1}),...outline.sections.flatMap(([heading,subsections],index)=>[block('heading',`${index+1} ${heading}`,{level:2}),...subsections.flatMap(([title,hint],subindex)=>[block('heading',`${index+1}.${subindex+1} ${title}`,{level:3}),block('paragraph',hint)])]),block('heading',`${outline.sections.length+1} ${outline.tableTitle}`,{level:2}),templateTable(outline.columns)]};
}
